import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('..', import.meta.url));
const args = ['--yes', '--package', '@yodaos-pkg/aix-cli@0.8.2', 'aix'];
const run = command => execFileSync('npx', [...args, ...command], { cwd: root, encoding: 'utf8' });
const help = run(['--help']);
if (!help.includes('aix pack') || !help.includes('aix list')) throw new Error('Installed AIX lacks pack/list');
mkdirSync(root + '/artifacts', { recursive: true });
mkdirSync(root + '/.aiui-evidence', { recursive: true });
const relative = 'artifacts/air-wx-en-ja-ko-zh.aix';
const packed = run(['pack', '.', '-o', relative, '--engine', '^0.17.0']);
const listing = run(['list', relative]);
if (/(^|[\s/])\.(git|aiui-evidence)(\/|\s|$)/im.test(listing)) throw new Error('Reserved directory leaked into AIX');
for (const required of ['app.json', 'app.js', 'pages/splash/index.ink', 'pages/weather/index.ink', 'pages/settings/index.ink', 'lib/weather.js']) if (!listing.includes(required)) throw new Error('Missing AIX entry: ' + required);
const hash = createHash('sha256').update(readFileSync(root + '/' + relative)).digest('hex');
writeFileSync(root + '/' + relative + '.sha256', hash + '  air-wx-en-ja-ko-zh.aix\n');
writeFileSync(root + '/.aiui-evidence/aix-pack.log', help + '\n' + packed); writeFileSync(root + '/.aiui-evidence/aix-list.log', listing);
console.log(packed.trim()); console.log(listing.trim()); console.log('SHA-256 ' + hash);
